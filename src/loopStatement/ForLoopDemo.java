package loopStatement;

public class ForLoopDemo {

	public static void main(String[] args) {
		
		
		for(int i = 1;i<= 6;i++) {
			if (i==6) {
				System.out.println(i);
				return;
			}
			
		}
		
		System.out.println("6 is not available");
		
	// array --> 10 transaction
		// loop --> for loop --> if
		
		
	}
	
}
