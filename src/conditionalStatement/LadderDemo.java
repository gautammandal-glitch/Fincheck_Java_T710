package conditionalStatement;

public class LadderDemo {

	public static void main(String[] args) {
		
		
		int i = 3;
		
		if (i==1) {
			System.out.println("hello 1");
		}else if (i==2) {
			System.out.println("hello 2");
		}else if (i==3) {
			System.out.println("hello 3");
		}else {
			System.out.println("hello else");
		}
		
		

	}

}
